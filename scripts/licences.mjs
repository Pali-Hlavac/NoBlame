// `pnpm licences`: writes the third-party notices NoBlame ships (src-tauri/resources/
// third-party-notices.txt): the licences of the Rust crates in the app (cargo-about), of the
// JavaScript packages in its page (pnpm), and of the syntax grammars and themes the diff colours
// with (two-face asks for them). `pnpm licences --check` fails when the file is out of date.
//
// cargo-about is built into `.cache/tools` on first use (inside the repository: Windows Defender
// blocks build scripts run from the temp folder).
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const CARGO_ABOUT_VERSION = "0.9.3";
const OUTPUT = "src-tauri/resources/third-party-notices.txt";
const TOOLS = resolve(".cache/tools");
const isWindows = process.platform === "win32";
const LICENCE_FILE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i;
const RULE = "=".repeat(80);

/**
 * Runs a command and returns its output; stops the script when it fails.
 * @param {string} command
 * @param {string[]} args
 * @param {boolean} [shell]
 */
function output(command, args, shell = false) {
  const result = spawnSync(command, args, {
    encoding: "utf8",
    shell,
    maxBuffer: 64 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  });
  if (result.status !== 0) {
    console.error(`${command} ${args.join(" ")} failed.`);
    process.exit(result.status ?? 1);
  }
  return result.stdout;
}

/** @param {string} text */
const unix = (text) => text.replace(/\r\n?/g, "\n");

function cargoAbout() {
  const binary = join(TOOLS, "bin", isWindows ? "cargo-about.exe" : "cargo-about");
  if (!existsSync(binary)) {
    console.log(`Building cargo-about ${CARGO_ABOUT_VERSION} into ${TOOLS}…`);
    const built = spawnSync(
      "cargo",
      [
        "install",
        "cargo-about",
        "--version",
        CARGO_ABOUT_VERSION,
        "--locked",
        "--features",
        "cli",
        "--root",
        TOOLS,
        "--target-dir",
        join(TOOLS, "cargo-target"),
      ],
      { stdio: "inherit" },
    );
    if (built.status !== 0) process.exit(built.status ?? 1);
  }
  return binary;
}

function rustCrates() {
  return output(cargoAbout(), [
    "generate",
    "--config",
    "scripts/licences/about.toml",
    "--manifest-path",
    "src-tauri/Cargo.toml",
    "scripts/licences/about.hbs",
  ]);
}

/** @param {string} folder */
function licenceText(folder) {
  const file = readdirSync(folder).find((name) => LICENCE_FILE.test(name));
  return file ? unix(readFileSync(join(folder, file), "utf8")).trim() : null;
}

function javascriptPackages() {
  /** @type {Record<string, { name: string; versions: string[]; paths: string[]; homepage?: string }[]>} */
  const byLicence = JSON.parse(output("pnpm", ["licenses", "list", "--prod", "--json"], isWindows));
  /** @type {Map<string, { licence: string; packages: string[] }>} */
  const byText = new Map();
  const missing = [];
  const packages = Object.entries(byLicence)
    .flatMap(([licence, list]) => list.map((pkg) => ({ licence, ...pkg })))
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const pkg of packages) {
    const label = `${pkg.name} ${pkg.versions.join(", ")}${pkg.homepage ? ` <${pkg.homepage}>` : ""}`;
    const text = pkg.paths[0] ? licenceText(pkg.paths[0]) : null;
    if (!text) {
      missing.push(`  - ${label} (${pkg.licence}; the package has no licence file)`);
      continue;
    }
    const entry = byText.get(text) ?? { licence: pkg.licence, packages: [] };
    entry.packages.push(`  - ${label}`);
    byText.set(text, entry);
  }
  const sections = [...byText].map(
    ([text, { licence, packages: used }]) =>
      `${RULE}\n${licence}\n\nUsed by:\n${used.join("\n")}\n\n${text}\n`,
  );
  if (missing.length > 0)
    sections.push(`${RULE}\nWithout a licence file:\n${missing.join("\n")}\n`);
  return { text: sections.join("\n"), count: packages.length };
}

function grammars() {
  return unix(
    output("cargo", ["run", "--quiet", "-p", "git-core", "--example", "grammar_licences"]),
  );
}

const rust = unix(rustCrates()).trim();
const javascript = javascriptPackages();
const notices = `NoBlame third-party notices

NoBlame includes the open-source software below. Each part names the components and the
licence they come with. Generated by \`pnpm licences\` from Cargo.lock and pnpm-lock.yaml.

Part 1: Rust crates
Part 2: JavaScript packages (${String(javascript.count)})
Part 3: Syntax grammars and colour themes (through two-face, from bat)


PART 1: RUST CRATES

${rust}


PART 2: JAVASCRIPT PACKAGES

${javascript.text}

PART 3: SYNTAX GRAMMARS AND COLOUR THEMES

${grammars().trim()}
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? unix(readFileSync(OUTPUT, "utf8")) : "";
  if (current !== notices) {
    console.error(`${OUTPUT} is out of date: run \`pnpm licences\` and commit it.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date.`);
} else {
  writeFileSync(OUTPUT, notices);
  console.log(`Wrote ${OUTPUT} (${String(Math.round(notices.length / 1024))} KB).`);
}
