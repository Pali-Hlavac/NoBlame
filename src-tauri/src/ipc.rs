//! Typed IPC surface: the single registry of commands and events exposed to the frontend
//! and the generator for `src/shared/ipc/bindings.ts` (ADR 0003).
//!
//! Adding a command: implement it in `<module>/commands.rs`, list it in [`builder`],
//! add it to `APP_COMMANDS` in `build.rs`, grant `allow-<command-name>` in
//! `capabilities/*.json`, then run `pnpm bindings`.

use std::path::{Path, PathBuf};

use specta_typescript::Typescript;
use tauri_specta::{Builder, collect_commands, collect_events};

use crate::{app_info, git_env, inspect, repository, settings, windows, workbench};

/// Location of the generated bindings, relative to the crate root.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
const BINDINGS_RELATIVE_PATH: &str = "../src/shared/ipc/bindings.ts";

/// Header prepended to the generated file.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
const BINDINGS_HEADER: &str = "// Generated by tauri-specta from src-tauri/src/ipc.rs. Do not edit by hand; run `pnpm bindings`.";

/// Builds the tauri-specta registry of every command the frontend may call.
pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        // The UI always sends complete objects, so one shape per type is enough.
        .disable_serde_phases()
        .events(collect_events![windows::RepositoriesRequested])
        .commands(collect_commands![
            app_info::commands::get_app_info,
            settings::commands::get_settings,
            settings::commands::update_settings,
            git_env::commands::get_git_info,
            windows::commands::get_window_context,
            windows::commands::take_repository_requests,
            windows::commands::open_task_window,
            repository::commands::open_repository,
            repository::commands::init_repository,
            repository::commands::close_repository,
            repository::commands::load_graph,
            repository::commands::get_graph_block,
            repository::commands::get_ancestry_block,
            repository::commands::get_commit_rows,
            repository::commands::write_commit_graph,
            repository::commands::list_recent_repositories,
            repository::commands::remove_recent_repository,
            inspect::commands::get_commit_details,
            inspect::commands::list_refs,
            inspect::commands::list_stashes,
            inspect::commands::list_submodules,
            workbench::commands::get_workbench_layout,
            workbench::commands::save_workbench_layout,
        ])
}

/// Absolute path of the generated TypeScript bindings.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
pub fn bindings_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_RELATIVE_PATH)
}

/// Writes TypeScript bindings for every registered command and type.
/// Only debug runs and `pnpm bindings` call it, hence unused in release builds.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
pub fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), specta_typescript::Error> {
    builder.export(
        Typescript::default().header(BINDINGS_HEADER),
        bindings_path(),
    )
}

#[cfg(test)]
mod tests {
    /// Regenerates the bindings; CI fails if the committed file differs afterwards.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::builder()).unwrap();
    }
}
